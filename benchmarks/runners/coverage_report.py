"""Summarise reports/coverage/*.jsonl into COVERAGE.md, coverage.csv and profile plots."""

from __future__ import annotations

import csv
import json
import math
from pathlib import Path

from run_coverage import HARD_NETLIB, SGM_SHIFT, SUITE_TITLES, SUITES

SOLVERS = (("sovereign", "Sovereign"), ("highs", "HiGHS"))
SOLVER_NAMES = dict(SOLVERS)


def load(out_dir: Path, suite: str) -> tuple[list[dict], dict]:
    path = out_dir / f"{suite}.jsonl"
    rows = [json.loads(l) for l in path.read_text().splitlines() if l.strip()] if path.exists() else []
    meta_path = out_dir / f"{suite}.meta.json"
    meta = json.loads(meta_path.read_text()) if meta_path.exists() else {}
    return rows, meta


def sgm(times: list[float], shift: float) -> float:
    return math.exp(sum(math.log(t + shift) for t in times) / len(times)) - shift if times else float("nan")


def solved(r: dict, key: str) -> bool:
    return r[key].get("outcome") == "SOLVED"


def capped(r: dict, key: str, limit: float) -> float:
    return min(r[key].get("time", limit), limit) if solved(r, key) else limit


def fmt_t(t: float | None) -> str:
    if t is None or (isinstance(t, float) and math.isnan(t)):
        return "-"
    return f"{t:.3f}" if t < 10 else f"{t:.1f}"


def suite_stats(rows: list[dict], limit: float, shift: float) -> dict:
    s = {"n": len(rows)}
    for key, _ in SOLVERS:
        s[key] = {o: sum(1 for r in rows if r[key].get("outcome") == o)
                  for o in ("SOLVED", "WRONG", "TIMEOUT", "FAILED")}
        s[key]["sgm_all"] = sgm([capped(r, key, limit) for r in rows], shift)
    both = [r for r in rows if solved(r, "sovereign") and solved(r, "highs")]
    s["both"] = len(both)
    s["only_sovereign"] = sum(1 for r in rows if solved(r, "sovereign") and not solved(r, "highs"))
    s["only_highs"] = sum(1 for r in rows if solved(r, "highs") and not solved(r, "sovereign"))
    s["sgm_both"] = {k: sgm([r[k]["time"] for r in both], shift) for k, _ in SOLVERS}
    # Head-to-head on instances both solve and at least one needs >= 0.1 s, so
    # millisecond timer noise does not decide wins.
    timed = [r for r in both if max(r["sovereign"]["time"], r["highs"]["time"]) >= 0.1]
    s["timed"] = len(timed)
    s["faster_sovereign"] = sum(1 for r in timed if r["sovereign"]["time"] < 0.9 * r["highs"]["time"])
    s["faster_highs"] = sum(1 for r in timed if r["highs"]["time"] < 0.9 * r["sovereign"]["time"])
    return s


def profile_plot(rows: list[dict], limit: float, title: str, path: Path) -> bool:
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception:
        return False
    if not rows:
        return False
    ratios = {k: [] for k, _ in SOLVERS}
    for r in rows:
        ts = {k: (max(r[k]["time"], 1e-3) if solved(r, k) else math.inf) for k, _ in SOLVERS}
        best = min(ts.values())
        for k in ts:
            ratios[k].append(ts[k] / best if math.isfinite(best) else math.inf)
    taus = [10 ** (i / 50) for i in range(0, 151)]
    fig, ax = plt.subplots(figsize=(6.4, 4.0), dpi=150)
    for (k, label), color in zip(SOLVERS, ("#0F766E", "#64748B")):
        ys = [sum(1 for x in ratios[k] if x <= tau) / len(rows) for tau in taus]
        ax.step(taus, ys, where="post", label=label, color=color, linewidth=2)
    ax.set_xscale("log")
    ax.set_ylim(0, 1.02)
    ax.set_xlabel("within this factor of the faster solver's time")
    ax.set_ylabel("fraction of instances solved")
    ax.set_title(f"{title}: performance profile ({len(rows)} instances, {int(limit)} s limit)", fontsize=9)
    ax.grid(True, which="both", alpha=0.25)
    ax.legend(loc="lower right", frameon=False)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)
    return True


def row_line(r: dict) -> str:
    def cell(k):
        x = r[k]
        o = x.get("outcome", "-")
        t = fmt_t(x.get("time"))
        return f"{o} {t}" if o in ("SOLVED", "TIMEOUT") else o
    size = f"{r.get('rows', '-')}×{r.get('cols', '-')}"
    return f"| {r['name']} | {size} | {cell('sovereign')} | {cell('highs')} |"


def write_report(out_dir: Path, md_path: Path) -> None:
    lines = ["# Coverage benchmark: Sovereign vs HiGHS", "",
             "Generated by `benchmarks/runners/run_coverage.py`. Inputs are fetched unmodified by",
             "`benchmarks/tools/fetch_coverage_corpus.py`; `datasets/coverage/corpus.json` pins their sha256.", "",
             "**Protocol.** Same input file for both solvers, one thread each, same wall-clock limit, each",
             "solver pinned to its own performance core and run side by side. MILP relative gap 1e-6 for",
             "both. Times are solve times (presolve included, file reading excluded); quick solved runs are",
             "timed up to 3 times and the median kept. For QP, HiGHS' `qp_nullspace_limit` is raised from its",
             "default 4000 to the number of variables; otherwise its active-set solver declines large models.", "",
             "**Scoring.** SOLVED means: claimed optimal (or infeasible, for the infeasible set), the returned",
             "point passes an independent check (bounds within 1e-6 of 1 + |bound|, rows within 1e-6 of",
             "1 + max(|rhs|, sum |a_ij x_j|) as in OSQP's relative criterion, integrality 1e-5), and its",
             "recomputed objective matches the published optimum (Netlib readme 1e-5, MIPLIB 2017 solu 1e-4,",
             "Maros-Meszaros 00README.QP 1e-5). Where both solvers' verified points agree and beat the published",
             "value, or one solver's point beats it while feasible to 1e-9 on every row and bound, it is disproved",
             "and the best such objective is used instead (listed per suite). WRONG means",
             "a claim that failed these checks. TIMEOUT counts as the time limit in the shifted geometric mean.",
             "Sovereign's branch-and-bound node limit is lifted so both MILP solvers stop only at the time limit;",
             "HiGHS's `large_matrix_value` is raised to 1e30 so it accepts every model's coefficients.", ""]
    csv_rows = []
    summary = ["| Suite | Instances | Sovereign solved | HiGHS solved | Sovereign wrong | HiGHS wrong | "
               "SGM time Sovereign | SGM time HiGHS |", "|---|---:|---:|---:|---:|---:|---:|---:|"]
    sections = []
    for suite in SUITES:
        rows, meta = load(out_dir, suite)
        if not rows:
            continue
        limit = float(meta.get("time_limit", 300))
        shift = SGM_SHIFT[suite]
        st = suite_stats(rows, limit, shift)
        so, hi = st["sovereign"], st["highs"]
        title = SUITE_TITLES[suite]
        summary.append(f"| {title} | {st['n']} | {so['SOLVED']} | {hi['SOLVED']} | {so['WRONG']} | {hi['WRONG']} | "
                       f"{fmt_t(so['sgm_all'])} s | {fmt_t(hi['sgm_all'])} s |")
        png = out_dir / f"profile-{suite}.png"
        has_plot = profile_plot(rows, limit, title, png)
        sec = [f"## {title}", "",
               f"Time limit {int(limit)} s, SGM shift {shift:g} s. Machine: {meta.get('cpu', '?')}, "
               f"{meta.get('platform', '?')}, HiGHS {meta.get('highs', '?')}.", "",
               "| | Sovereign | HiGHS |", "|---|---:|---:|"]
        for o in ("SOLVED", "WRONG", "TIMEOUT", "FAILED"):
            sec.append(f"| {o.title()} | {so[o]} | {hi[o]} |")
        sec += [f"| Shifted geometric mean, all instances (s) | {fmt_t(so['sgm_all'])} | {fmt_t(hi['sgm_all'])} |",
                f"| Shifted geometric mean, {st['both']} solved by both (s) | {fmt_t(st['sgm_both']['sovereign'])} | "
                f"{fmt_t(st['sgm_both']['highs'])} |",
                f"| Solved only by this solver | {st['only_sovereign']} | {st['only_highs']} |",
                f"| Faster by >10% (of {st['timed']} both-solved instances taking ≥0.1 s) | "
                f"{st['faster_sovereign']} | {st['faster_highs']} |", ""]
        if has_plot:
            sec += [f"![{title} performance profile](coverage/{png.name})", ""]
        if suite == "netlib":
            hard = [r for r in rows if r["name"] in HARD_NETLIB]
            if hard:
                sec += ["### Degenerate and numerically hard Netlib models", "",
                        "| Instance | Rows×Cols | Sovereign | HiGHS |", "|---|---|---|---|"]
                sec += [row_line(r) for r in sorted(hard, key=lambda r: r["name"])] + [""]
        disproved = [r for r in rows if r.get("reference_disproved")]
        if disproved:
            sec += ["### Published optima disproved by a verified point", "",
                    "Either both solvers returned verified points that agree and beat the published value, or the",
                    "listed solver's point beat it while feasible to 1e-9 on every row and bound. These instances",
                    "were scored against the best such objective.", "",
                    "| Instance | Published | Best verified | Found by |", "|---|---:|---:|---|"]
            for r in disproved:
                d = r["reference_disproved"]
                sec.append(f"| {r['name']} | {d['published']:.10g} | {d['best_verified']:.10g} | "
                           f"{', '.join(SOLVER_NAMES.get(k, k) for k in d['by'])} |")
            sec.append("")
        wrong = [r for r in rows if r["sovereign"].get("outcome") == "WRONG"]
        if wrong:
            sec += ["### Sovereign answers that failed verification", "",
                    "| Instance | Status | Reason | Max row viol. | Max bound viol. | Rel. obj. error |",
                    "|---|---|---|---:|---:|---:|"]
            for r in wrong:
                x, c = r["sovereign"], r["sovereign"].get("check") or {}
                sec.append(f"| {r['name']} | {x.get('status')} | {x.get('why', '')} | "
                           f"{c.get('max_row_violation', float('nan')):.1e} | "
                           f"{c.get('max_bound_violation', float('nan')):.1e} | "
                           f"{x.get('ref_rel_error', float('nan')):.1e} |")
            sec.append("")
        cross = out_dir / f"{suite}_highs_qps_crosscheck.jsonl"
        if cross.exists():
            cc = [json.loads(line) for line in cross.read_text().splitlines() if line.strip()]
            sec += ["### HiGHS misses re-run from the original QPS files", "",
                    "HiGHS here receives the same model as Sovereign, converted from the Maros-Meszaros MAT files.",
                    "To rule out the conversion, `benchmarks/tools/highs_qps_crosscheck.py` re-ran every instance",
                    "HiGHS did not solve with HiGHS reading the original QPS file itself (`readModel`, default",
                    "options, one thread, 300 s). With the",
                    "default `qp_nullspace_limit` some large models stop at once with a solve error instead of",
                    "running to the time limit.", "",
                    "| Instance | Harness outcome | HiGHS on QPS file | Objective | Published |",
                    "|---|---|---|---:|---:|"]
            for c in sorted(cc, key=lambda c: c["name"]):
                has_point = c.get("status") in ("Optimal", "Time limit reached")
                obj = f"{c['obj']:.10g}" if has_point else ""
                sec.append(f"| {c['name']} | {c.get('harness')} | {c.get('status', c.get('error', '?'))} | "
                           f"{obj} | {c.get('reference')} |")
            sec.append("")
        sec += ["<details><summary>All instances</summary>", "",
                "| Instance | Rows×Cols | Sovereign | HiGHS |", "|---|---|---|---|"]
        sec += [row_line(r) for r in sorted(rows, key=lambda r: r["name"].lower())]
        sec += ["", "</details>", ""]
        sections += sec
        for r in rows:
            csv_rows.append({"suite": suite, "instance": r["name"], "rows": r.get("rows"), "cols": r.get("cols"),
                             "nnz": r.get("nnz"), "integers": r.get("integers"),
                             "reference": (r.get("reference") or {}).get("value"),
                             **{f"{k}_{f}": r[k].get(f) for k, _ in SOLVERS
                                for f in ("status", "outcome", "time", "objective", "ref_rel_error", "primal_gap")}})
    lines += ["## Summary", ""] + summary + [""] + sections
    md_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    if csv_rows:
        with (out_dir / "coverage.csv").open("w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(csv_rows[0].keys()))
            w.writeheader()
            w.writerows(csv_rows)
    print(f"wrote {md_path}")
