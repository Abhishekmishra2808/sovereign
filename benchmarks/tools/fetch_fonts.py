"""One-shot helper: download Inter + Outfit woff2 files and rewrite the CSS to
point at local copies, so the built bundle has zero CDN references.

Development tool only. The generated files under sovereign-frontend/public/fonts are committed
so that a clean checkout builds offline without running this.
"""
from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # benchmarks/tools/ -> repo root
OUT = ROOT.parent / "sovereign-frontend" / "public" / "fonts"

# A browser UA is required: Google Fonts only serves woff2 (not ttf) to modern
# user agents, and ttf roughly triples the payload.
UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)
SRC = (
    "https://fonts.googleapis.com/css2"
    "?family=Inter:wght@400;500;600;700&family=Outfit:wght@400;500;600&display=swap"
)

# Google Fonts emits a separate @font-face per unicode subset. We keep only the
# Latin ones: that is the actual product language, and bundling cyrillic/greek/
# vietnamese would triple the offline payload for glyphs we never render.
KEEP_SUBSETS = {"latin", "latin-ext"}
BLOCK = re.compile(r"/\*\s*([a-z0-9-]+)\s*\*/\s*(@font-face\s*\{.*?\n\})", re.S)
FONT_URL = re.compile(r"url\((https://[^)]+)\)")


def split_blocks(raw: str) -> list[tuple[str, str]]:
    """Return [(subset, font_face_block)] preserving document order."""
    return BLOCK.findall(raw)


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=45) as resp:
        return resp.read()


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    raw = fetch(SRC).decode("utf-8")

    # Keep only the subsets we ship, preserving document order.
    all_blocks = split_blocks(raw)
    if not all_blocks:
        print("ERROR: could not parse @font-face blocks from the stylesheet", file=sys.stderr)
        return 1

    kept_blocks = [b for subset, b in all_blocks if subset in KEEP_SUBSETS]
    dropped = sorted({s for s, _ in all_blocks} - KEEP_SUBSETS)
    print(f"parsing {len(all_blocks)} blocks; keeping {sorted(KEEP_SUBSETS)}, dropping {dropped}")
    if not kept_blocks:
        print("ERROR: no latin subsets found", file=sys.stderr)
        return 1

    # Rewrite each block's URL to a local path before joining, so a local name
    # can be derived from that block's own family/weight/subset.
    rewritten: list[str] = []
    for block in kept_blocks:
        match = FONT_URL.search(block)
        if match is None:
            continue
        remote = match.group(1)

        family_m = re.search(r"font-family:\s*'([^']+)'", block)
        weight_m = re.search(r"font-weight:\s*(\d+)", block)
        if family_m is None or weight_m is None:
            print(f"ERROR: could not read family/weight from block:\n{block}", file=sys.stderr)
            return 1
        family = family_m.group(1)
        weight = weight_m.group(1)

        # Distinguish the two latin subsets by whether the range covers U+0100
        # (latin-ext: Latin Extended-A) or not.
        range_m = re.search(r"unicode-range:\s*([^;]+);", block)
        subset = "latin-ext" if range_m and "U+0100" in range_m.group(1) else "latin"

        name = f"{family.lower()}-{weight}-{subset}.woff2"
        dest = OUT / name
        if not dest.exists():
            dest.write_bytes(fetch(remote))
        print(f"  {name}  {dest.stat().st_size // 1024} KB")

        rewritten.append(block.replace(remote, f"/fonts/{name}"))

    css = "\n".join(rewritten)

    header = (
        "/* Self-hosted Inter + Outfit (latin + latin-ext subsets only).\n"
        " *\n"
        " * Generated by benchmarks/tools/fetch_fonts.py and committed to the repo so\n"
        " * a clean checkout builds with no network access. The offline-first\n"
        " * requirement demands this: a Google Fonts @import in index.css is what\n"
        " * previously prevented Sovereign from running without a network.\n"
        " *\n"
        " * Do NOT reintroduce a remote @import. If you need another family or\n"
        " * subset, add it here and re-run the script.\n"
        " */\n"
    )
    (OUT / "fonts.css").write_text(header + css, encoding="utf-8")

    remaining = re.findall(r"https?://[^\s)]+", css)
    if remaining:
        print("ERROR: remote references remain in fonts.css:", remaining, file=sys.stderr)
        return 1

    total = sum(p.stat().st_size for p in OUT.glob("*.woff2")) // 1024
    print(f"wrote {OUT / 'fonts.css'}; {len(rewritten)} faces, {total} KB total, no remote refs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
